CREATE TABLE IF NOT EXISTS teacher_directory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_row INTEGER NOT NULL UNIQUE,
    name TEXT NOT NULL,
    gender VARCHAR(16),
    position TEXT,
    disciplines JSONB NOT NULL DEFAULT '[]'::jsonb,
    institution TEXT NOT NULL,
    edu_level TEXT,
    academic_degree TEXT,
    academic_title TEXT,
    qualification TEXT,
    experience INTEGER,
    experience_text TEXT,
    education_details JSONB NOT NULL DEFAULT '[]'::jsonb,
    professional_development JSONB NOT NULL DEFAULT '[]'::jsonb,
    professional_retraining JSONB NOT NULL DEFAULT '[]'::jsonb,
    source_url TEXT NOT NULL,
    parsed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_teacher_directory_name ON teacher_directory (name);

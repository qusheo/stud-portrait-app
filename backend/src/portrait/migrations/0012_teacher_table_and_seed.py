# Creates the `teacher` table (mirrors create_database.sql) and, when the
# restored elibrary_sample dataset is present, seeds it from that directory.
# Both steps are idempotent so the migration is safe on any environment.

from django.db import migrations


CREATE_TEACHER = """
CREATE TABLE IF NOT EXISTS teacher (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_row INTEGER NOT NULL UNIQUE,
    name TEXT NOT NULL,
    gender VARCHAR(16),
    position TEXT,
    disciplines JSONB NOT NULL DEFAULT '[]'::jsonb,
    institution TEXT NOT NULL,
    edu_level TEXT,
    academic_degree TEXT,
    academic_title TEXT,
    qualification TEXT,
    experience INTEGER,
    experience_text TEXT,
    education_details JSONB NOT NULL DEFAULT '[]'::jsonb,
    professional_development JSONB NOT NULL DEFAULT '[]'::jsonb,
    professional_retraining JSONB NOT NULL DEFAULT '[]'::jsonb,
    source_url TEXT NOT NULL,
    parsed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_teacher_name ON teacher (name);
"""

DROP_TEACHER = "DROP TABLE IF EXISTS teacher;"


def seed_teachers(apps, schema_editor):
    with schema_editor.connection.cursor() as cursor:
        cursor.execute(
            "SELECT 1 FROM information_schema.tables "
            "WHERE table_schema='elibrary_sample' AND table_name='teacher'"
        )
        if not cursor.fetchone():
            return
        cursor.execute("SELECT 1 FROM teacher LIMIT 1")
        if cursor.fetchone():
            return
        cursor.execute(
            "INSERT INTO teacher (id, source_row, name, institution, source_url) "
            "SELECT id, source_row, name, institution, '' "
            "FROM elibrary_sample.teacher ORDER BY id"
        )


class Migration(migrations.Migration):

    dependencies = [
        ("portrait", "0011_teacher_table"),
    ]

    operations = [
        migrations.RunSQL(CREATE_TEACHER, reverse_sql=DROP_TEACHER),
        migrations.RunPython(seed_teachers, reverse_code=migrations.RunPython.noop),
    ]
